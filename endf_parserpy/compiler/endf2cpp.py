from . import cpp_boilerplate
from . import cpp_boilerplate_reading
from . import cpp_primitives as cpp
from .code_generator_parsing import generate_all_cpp_parsefuns_code
from .code_generator_writing import generate_all_cpp_writefuns_code
from hashlib import md5


def generate_cpp_module_code(
    recipes, module_name, shared_registry=None, tape_structure=None
):
    """Emit one ENDF flavor's pybind11 module source.

    When ``shared_registry`` is provided, the heavy per-(mf, mt) parse and
    write function bodies are routed into the registry under canonical
    names derived from the recipe text and the MF/MT it is specialized
    for, and the per-flavor source emits only
    forward declarations plus the dispatchers, the wrappers called from
    Python and the PYBIND11_MODULE block. The caller is responsible for
    emitting the accumulated registry as the shared translation unit(s)
    compiled once (see :func:`generate_shared_cpp_code`).
    """
    parsefuns_code, parsefuns_pybind_glue = generate_all_cpp_parsefuns_code(
        recipes,
        module_name,
        shared_registry=shared_registry,
        tape_structure=tape_structure,
    )
    writefuns_code, writefuns_pybind_glue = generate_all_cpp_writefuns_code(
        recipes,
        module_name,
        shared_registry=shared_registry,
        tape_structure=tape_structure,
    )

    funs_code = parsefuns_code + writefuns_code
    pybind_glue = parsefuns_pybind_glue + writefuns_pybind_glue

    module_header = cpp_boilerplate.module_header()
    pybind_glue = cpp_boilerplate.register_pybind_module(module_name, pybind_glue)
    code = module_header + funs_code + pybind_glue

    md5hash = md5(code.encode()).hexdigest()
    header = "// File generated by endf_parserpy.compiler.endf2cpp.py::generate_cpp_module_code\n"
    header += "// MD5 hash of file content below this line: "
    header += md5hash
    header += "\n"
    return header + code


def flavor_namespace(entry_name):
    """The C++ namespace of the functions of a flavor in the module with
    all flavors, e.g. ``endf_flavor_endf6_ext`` for the entry
    ``endf6_ext``."""
    return f"endf_flavor_{entry_name}"


def _generate_flavor_parts(
    recipes, entry_name, shared_registry=None, tape_structure=None
):
    # the declarations of the shared functions that the flavor calls,
    # which must stay in the global namespace, and the code of the
    # flavor (wrappers, dispatchers and the registration of its
    # functions) in its namespace
    forward_decls = []
    parsefuns_code, parsefuns_pybind_glue = generate_all_cpp_parsefuns_code(
        recipes,
        entry_name,
        shared_registry=shared_registry,
        forward_decls=forward_decls,
        tape_structure=tape_structure,
    )
    writefuns_code, writefuns_pybind_glue = generate_all_cpp_writefuns_code(
        recipes,
        entry_name,
        shared_registry=shared_registry,
        forward_decls=forward_decls,
        tape_structure=tape_structure,
    )
    pybind_glue = parsefuns_pybind_glue + writefuns_pybind_glue
    namespace = flavor_namespace(entry_name)
    code = cpp.line(f"namespace {namespace} {{")
    code += cpp.line("")
    code += parsefuns_code + writefuns_code
    code += cpp.line("")
    code += cpp.line("void register_functions(py::module_& m) {")
    code += cpp.indent_code(pybind_glue, cpp.INDENT)
    code += cpp.close_block()
    code += cpp.line("")
    code += cpp.line(f"}}  // namespace {namespace}")
    return "".join(forward_decls), code


def _with_md5_header(code, function_name):
    md5hash = md5(code.encode()).hexdigest()
    header = (
        f"// File generated by endf_parserpy.compiler.endf2cpp.py::{function_name}\n"
    )
    header += "// MD5 hash of file content below this line: "
    header += md5hash
    header += "\n"
    return header + code


def generate_cpp_flavor_code(
    recipes, entry_name, shared_registry=None, tape_structure=None
):
    """Emit the translation unit of one flavor of the module with all
    flavors.

    The code of the flavor is placed into the namespace
    ``endf_flavor_<entry_name>``, so that the functions of the flavors,
    which have the same names in every flavor (e.g. ``parse_endf``), can
    be linked into one module. The function
    ``endf_flavor_<entry_name>::register_functions`` defines the
    functions of the flavor in a (sub)module; the module init in the
    code of :func:`generate_cpp_flavors_module_code` calls it.
    """
    forward_decls, flavor_code = _generate_flavor_parts(
        recipes, entry_name, shared_registry, tape_structure
    )
    code = cpp_boilerplate.module_header() + forward_decls + flavor_code
    return _with_md5_header(code, "generate_cpp_flavor_code")


def _flavors_module_init(module_name, entry_names):
    code = cpp.line("")
    for entry_name in entry_names:
        code += cpp.line(f"namespace {flavor_namespace(entry_name)} {{")
        code += cpp.statement("void register_functions(py::module_& m)", cpp.INDENT)
        code += cpp.line("}")
    code += cpp.line("")
    code += cpp.line("namespace {")
    code += cpp.line("")
    code += cpp.line("void cpp_register_diagnostics(py::module_& m) {")
    code += cpp.indent_code(
        cpp_boilerplate_reading.register_diagnostic_functions(), cpp.INDENT
    )
    code += cpp.close_block()
    code += cpp.line("")
    code += cpp.indent_code(
        r"""
        // one submodule per flavor, which is also entered into sys.modules,
        // so that importlib.import_module(func.__module__) finds it
        void cpp_register_flavor(
          py::module_& m, py::object& sys_modules, const char* entry_name,
          void (*register_functions)(py::module_&)
        ) {
          py::module_ sub = m.def_submodule(entry_name);
          register_functions(sub);
          cpp_register_diagnostics(sub);
          sys_modules[sub.attr("__name__")] = sub;
        }
        """,
        -8,
    ).lstrip("\n")
    code += cpp.line("")
    code += cpp.line("}  // namespace")
    code += cpp.line("")
    code += cpp.line("")
    code += cpp.line(f"PYBIND11_MODULE({module_name}, m) {{")
    code += cpp.indent_code(cpp_boilerplate_reading.row_selection_warning(), cpp.INDENT)
    code += cpp.statement("cpp_register_diagnostics(m)", cpp.INDENT)
    code += cpp.statement(
        'py::object sys_modules = py::module_::import("sys").attr("modules")',
        cpp.INDENT,
    )
    for entry_name in entry_names:
        code += cpp.statement(
            f'cpp_register_flavor(m, sys_modules, "{entry_name}", '
            f"&{flavor_namespace(entry_name)}::register_functions)",
            cpp.INDENT,
        )
    entries = ", ".join(f'"{e}"' for e in entry_names)
    code += cpp.comment(
        "the names of the flavor entries, in the order of the build targets", cpp.INDENT
    )
    code += cpp.statement(f'm.attr("_entries") = py::make_tuple({entries})', cpp.INDENT)
    code += cpp.close_block()
    return code


def generate_cpp_flavors_module_code(module_name, entry_names):
    """Emit the module init of the module with all flavors.

    The code of the flavors is in translation units of their own (see
    :func:`generate_cpp_flavor_code`), whose functions
    ``register_functions`` the module init calls.

    Parameters
    ----------
    module_name : str
        The name of the extension module, e.g. ``_flavors``.
    entry_names : list[str]
        The entry names of the build targets (``cpp_module_basename``).
    """
    code = cpp_boilerplate.module_header()
    code += _flavors_module_init(module_name, entry_names)
    return _with_md5_header(code, "generate_cpp_flavors_module_code")


def generate_shared_cpp_code(shared_registry, num_chunks=1):
    """Emit the shared TU(s) that hold every unique
    ``parse_recipe_<hash>_istream`` / ``write_recipe_<hash>_ostream`` body
    collected across all flavors. They are linked once into the module
    with all flavors, together with the translation units of the flavors
    (see :func:`generate_cpp_flavor_code`).

    Parameters
    ----------
    shared_registry : dict
        Registry populated by the per-flavor codegen pass. Keys
        ``"parse"`` and ``"write"`` each map ``recipe_hash`` to
        ``(canonical_name, function_code)``.
    num_chunks : int
        Number of output translation units to spread the canonical
        functions across. ``num_chunks > 1`` lets the build system
        compile the shared bodies in parallel. The functions are
        assigned by size (see :func:`balanced_chunk_assignment` and
        :func:`_code_size`), so that the chunks take about the same
        time to compile; the assignment depends only on the generated
        code, so the same recipes give the same chunks on every run. The
        canonical functions never call each other and need only the module
        header, so a function can land in any chunk, and the parse and
        write functions of a recipe in different ones.

    Returns
    -------
    list[tuple[str, str]]
        A list of ``(basename, source_text)`` pairs. With
        ``num_chunks == 1`` the list has a single entry named
        ``_shared.cpp`` (the legacy single-TU layout). Chunks without
        functions are left out.
    """
    parse_reg = shared_registry.get("parse", {})
    write_reg = shared_registry.get("write", {})
    # Within a chunk, the functions are in the lexicographic order of
    # their dedup keys (recipe text and MF/MT), parse functions first.
    parse_items = sorted(parse_reg.items())
    write_items = sorted(write_reg.items())
    if num_chunks <= 1:
        return [("_shared.cpp", _format_shared_chunk(parse_items, write_items, None))]

    sized_items = [
        (("parse", recipe_hash), _code_size(code, "parse"))
        for recipe_hash, (_canonical, code) in parse_items
    ] + [
        (("write", recipe_hash), _code_size(code, "write"))
        for recipe_hash, (_canonical, code) in write_items
    ]
    assignment = balanced_chunk_assignment(sized_items, num_chunks)
    chunks = []
    for chunk_id, keys in enumerate(assignment):
        members = set(keys)
        chunk_parse = [it for it in parse_items if ("parse", it[0]) in members]
        chunk_write = [it for it in write_items if ("write", it[0]) in members]
        if not chunk_parse and not chunk_write:
            continue
        basename = f"_shared_part_{chunk_id:02d}.cpp"
        chunks.append(
            (basename, _format_shared_chunk(chunk_parse, chunk_write, chunk_id))
        )
    return chunks


# The weights of the source bytes of the parse and write functions in
# the estimate of their compile time (see _code_size). With GCC 13 at
# -O1, the compile time of a shared chunk was about 5 s for the module
# header plus 9 s per MB of parse functions and 14 s per MB of write
# functions, i.e. a byte of a write function costs about 3/2 of a byte
# of a parse function (fitted to the 16 chunks of two layouts).
_CODE_SIZE_WEIGHTS = {"parse": 2, "write": 3}


def _code_size(code, side):
    """The size of a generated function as the measure of its compile
    time: the length of its source in bytes, weighted by the kind of the
    function (``side``, ``"parse"`` or ``"write"``). An integer, so that
    the assignment is exact."""
    return _CODE_SIZE_WEIGHTS[side] * len(code.encode())


def balanced_chunk_assignment(sized_items, num_chunks):
    """Assign items to ``num_chunks`` chunks with about equal total sizes.

    The items are taken largest first, each into the chunk with the
    smallest total so far (the longest-processing-time rule); ties are
    broken by the key of the item (for equal sizes) and by the lowest
    chunk number (for equal totals). The result depends only on the
    keys and sizes, not on the order of ``sized_items``. The largest
    total exceeds the smallest one by at most the largest size, and is
    at most 4/3 of the largest total of the best possible assignment.

    Parameters
    ----------
    sized_items : iterable of tuple
        Pairs ``(key, size)``, with distinct, mutually comparable keys
        and non-negative sizes.
    num_chunks : int
        The number of chunks (at least 1).

    Returns
    -------
    list[list]
        For each chunk, the keys of its items in the order of their
        assignment. Chunks may be empty if there are fewer items than
        chunks; these are the last ones.
    """
    num_chunks = max(int(num_chunks), 1)
    items = sorted(sized_items, key=lambda it: (-it[1], it[0]))
    keys = [key for key, _size in items]
    if len(set(keys)) != len(keys):
        raise ValueError("the keys of the items must be distinct")
    totals = [0] * num_chunks
    assignment = [[] for _ in range(num_chunks)]
    for key, size in items:
        chunk_id = min(range(num_chunks), key=lambda i: (totals[i], i))
        assignment[chunk_id].append(key)
        totals[chunk_id] += size
    return assignment


def _format_shared_chunk(parse_items, write_items, chunk_id):
    parts = [cpp_boilerplate.module_header()]
    chunk_tag = "" if chunk_id is None else f" (chunk {chunk_id})"
    parts.append(
        f"// === Deduplicated parse functions{chunk_tag} "
        "(canonical names derived from recipe and MF/MT) ===\n"
    )
    for recipe_hash, (_canonical, code) in parse_items:
        parts.append(code)
    parts.append(
        f"\n// === Deduplicated write functions{chunk_tag} "
        "(canonical names derived from recipe and MF/MT) ===\n"
    )
    for recipe_hash, (_canonical, code) in write_items:
        parts.append(code)
    body = "".join(parts)
    md5hash = md5(body.encode()).hexdigest()
    header = (
        "// File generated by endf_parserpy.compiler.endf2cpp.py::generate_shared_cpp_code\n"
        "// MD5 hash of file content below this line: " + md5hash + "\n"
    )
    return header + body
